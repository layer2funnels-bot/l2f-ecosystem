for (const t of builtinTemplates()) {
  mig += `insert into public.templates (owner_id, builtin_key, name, category, description, graph, settings)\nvalues (null, ${q(t.key)}, ${q(t.name)}, ${q(t.category)}, ${q(t.description)}, ${j(t.graph)}, ${j(t.settings)})\non conflict (builtin_key) do update set name = excluded.name, category = excluded.category, description = excluded.description, graph = excluded.graph, settings = excluded.settings;\n\n`;
}
writeFileSync("supabase/migrations/20261001000100_builtin_templates.sql", mig);

