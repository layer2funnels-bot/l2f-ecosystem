// Builds apps/web/v8.css from the approved Design V8 "Ledger" prototype stylesheets
// (docs/design/v8/.../08_PROTOTYPE_AND_SOURCE/prototype-source: v5.css, v6.css, v7.css, v8.css).
// The V8 prototype sits on exactly the same base.css + v4.css + extra.css as Design v4 (byte-identical), which the app already
// ships as apps/web/v4.css (scripts/build-v4css.mjs). This file is the layer on top, derived from the prototype rather than retyped.
// Same rules as the v4 build: colour tokens belong to packages/ui/tokens.css (built from tokens.json, contrast-checked), so the
// prototype's colour blocks are dropped; demo-only controls are dropped. Funnel Mapper styles are confined to `.fmpx` exactly as the
// prototype's own build does (port of prototype-source/scope.py), so they can never leak into other apps (V8_BUG_FIXES #1).
// Run: node scripts/build-v8css.mjs   (--check: fail if apps/web/v8.css is stale)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const dir = new URL('../docs/design/v8/Layer2Funnels_V8_Developer_Handoff/08_PROTOTYPE_AND_SOURCE/prototype-source/', import.meta.url);
const read = (f) => readFileSync(new URL(f, dir), 'utf8');

// ---- port of scope.py ----
const SKIP = new Set(['fmpx', 'shell', 'ed', 'on', 'new', 'live', 'sm', 'big', 'six', 'three', 'no', 'd', 'grow']);
function pref(s, fm) {
  s = s.trim();
  if (!s || s.startsWith('.fmpx') || s.startsWith('.shell.fmpx')) return s;
  if (fm) { const m = /^\.([\w-]+)/.exec(s); if (!m || !fm.has(m[1])) return s; }
  return '.fmpx ' + s;
}
const scopeRules = (css, fm) => css.replace(/([^{}]+)\{([^{}]*)\}/g, (_, sel, body) => sel.split(',').map((x) => pref(x, fm)).join(',') + '{' + body + '}');
function scopeMedia(css, fm) {
  let out = ''; let i = 0;
  const re = /@media[^{]*\{((?:[^{}]*\{[^{}]*\})*)\s*\}/g; let m;
  while ((m = re.exec(css))) { const s = m.index + m[0].indexOf('{') + 1; out += css.slice(i, s) + scopeRules(m[1], fm); i = s + m[1].length; }
  return out + css.slice(i);
}
function fmScoped(v6, v7) {
  let L = v6.split('\n');
  let a = L.findIndex((l) => l.includes('FMP v6: its own dark identity'));
  let b = L.findIndex((l) => l.includes('Whiteboard full page'));
  const sec = L.slice(a + 1, b).join('\n');
  const fm = new Set([...sec.replace(/\{[^}]*\}/g, '{}').matchAll(/\.([\w-]+)/g)].map((x) => x[1]).filter((x) => !SKIP.has(x)));
  v6 = [...L.slice(0, a + 1), scopeRules(sec), ...L.slice(b)].join('\n');
  L = v7.split('\n');
  a = L.findIndex((l) => l.includes('Funnel Mapper: one step larger'));
  b = L.findIndex((l, i) => i > a && l.startsWith('/*'));
  v7 = [...L.slice(0, a + 1), scopeRules(L.slice(a + 1, b).join('\n')), ...L.slice(b)].join('\n');
  return [scopeMedia(v6, fm), scopeMedia(v7, fm)];
}

// ---- assemble ----
const [v6, v7] = fmScoped(read('v6.css'), read('v7.css'));
// colour token blocks (tokens.css owns colours) and demo-only controls are dropped; sizing variables on :root are kept (they are V8 values)
const colourBlock = (l) => /^(\[data-theme="(light|dark)"\]|\[data-org="(l2f|aurj)"\](\[data-theme="(light|dark)"\])?)\{--(bg|surface|text|brand|action)/.test(l);
const drop = (l) => colourBlock(l) || /^\.(demo|demo-fab)\b/.test(l) || /^\.demo[ .:{[]/.test(l) || /#demofab\b/.test(l) && /^#demofab/.test(l);
const own = (l) => /^\s*\.(toast|scrim)\b/.test(l) || /^\s*#toasts\b/.test(l);
const layers = [['v5.css', read('v5.css')], ['v6.css', v6], ['v7.css', v7], ['v8.css', read('v8.css')]];
const body = layers.map(([name, css]) => `/* ===== ${name} ===== */\n` + css.split('\n').filter((l) => !drop(l) && !own(l))
  // the app's navigation items are links: every `.nav button` / `.bbar button` rule also covers `a` (same as the v4 build)
  .flatMap((l) => (/\.(nav|bbar|appmenu \.grid)(\s\.sub)? button/.test(l) && /^[.@ ]/.test(l) && !l.startsWith('@') ? [l, l.replace(/\.(nav|bbar|appmenu \.grid)(\s\.sub)? button/g, '.$1$2 a')] : [l]))
  .join('\n')).join('\n');
const head = '/* GENERATED by scripts/build-v8css.mjs from docs/design/v8 prototype-source (v5.css, v6.css, v7.css, v8.css; Funnel Mapper scoped to .fmpx). Do not edit by hand. */\n';
const css = head + body + '\n';
const out = new URL('../apps/web/v8.css', import.meta.url);
if (process.argv.includes('--check')) {
  const ok = existsSync(out) && readFileSync(out, 'utf8') === css;
  console.log(ok ? 'PASS v8.css up to date' : 'FAIL v8.css stale: run node scripts/build-v8css.mjs'); process.exit(ok ? 0 : 1);
}
writeFileSync(out, css);
console.log(`v8.css: ${css.split('\n').length} lines`);
