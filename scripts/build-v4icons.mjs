// Builds apps/web/js/icons-v4.js from the approved Design v4 icon set (docs/design/v4/prototype-source/reuse.js): same drawings, converted to the
// (reuse.js and the second set in core.js) element lists that icon() builds with createElementNS (never parsed from markup at runtime). Run: node scripts/build-v4icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(new URL('../docs/design/v4/prototype-source/reuse.js', import.meta.url), 'utf8');
const body = src.slice(src.indexOf('const I={') + 9, src.indexOf('};\nconst ic='));
const core = readFileSync(new URL('../docs/design/v4/prototype-source/core.js', import.meta.url), 'utf8');
const more = core.slice(core.indexOf("Object.assign(I,{") + 17, core.indexOf('});\nAPPS.forEach'));
const I = Function(`"use strict";return ({${body},${more}})`)();
const out = {};
for (const [name, markup] of Object.entries(I)) {
  const els = [];
  for (const m of markup.matchAll(/<(\w+)([^>]*?)\/?>/g)) {
    const attrs = {}; for (const a of m[2].matchAll(/([\w:-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    els.push([m[1], attrs]);
  }
  out[name] = els;
}
writeFileSync(new URL('../apps/web/js/icons-v4.js', import.meta.url), `// GENERATED by scripts/build-v4icons.mjs from docs/design/v4/prototype-source/reuse.js. Do not edit by hand.\nexport const V4_ICONS = ${JSON.stringify(out)};\n`);
console.log(Object.keys(out).length, 'icons');
